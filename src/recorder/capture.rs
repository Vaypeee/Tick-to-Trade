//! The record written to disk, and the clock it is stamped with.

use std::fmt::Write as _;
use std::time::{Instant, SystemTime, UNIX_EPOCH};

use serde_json::value::RawValue;

/// Timestamps taken at the moment a frame comes off the socket.
///
/// Both clocks are recorded because neither is sufficient on its own. The
/// monotonic reading is the one to measure durations with: it cannot jump when
/// NTP steps the system clock mid-recording. The wall clock is the only one
/// that can be correlated with a recording taken by another process or on
/// another machine, which is the whole point of recording two feeds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Stamp {
    pub unix_ns: u64,
    pub mono_ns: u64,
}

impl Stamp {
    /// Reads both clocks, monotonic first: it is the cheaper call, so it lands
    /// closer to the frame's actual arrival.
    pub fn now(origin: Instant) -> Self {
        let mono_ns = origin.elapsed().as_nanos() as u64;
        let unix_ns = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|since| since.as_nanos() as u64)
            .unwrap_or(0);
        Self { unix_ns, mono_ns }
    }
}

/// What a recorded line holds.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Payload {
    /// A frame that parsed as JSON, stored verbatim rather than re-serialised:
    /// the analysis should see exactly what the exchange sent.
    Json(String),
    /// A frame that was not JSON, such as the `PONG` reply to a keepalive.
    Text(String),
    /// A marker generated by the recorder itself. Connection lifecycle events
    /// are data too: without them, a gap in the recording is indistinguishable
    /// from a quiet market.
    Control {
        kind: &'static str,
        detail: Option<String>,
    },
    /// A click on the spectator-baseline page.
    ///
    /// `clicked` is the browser's own clock reading at the moment of the
    /// press, kept separate from the instant the server wrote it down. Both
    /// run on the same machine clock, so the gap between them is the cost of
    /// the loopback round trip and nothing else — small, but measured rather
    /// than assumed, like every other number here.
    Label {
        id: String,
        direction: String,
        clicked: Stamp,
    },
    /// An HTTP poll whose body differed from the previous one.
    ///
    /// A polled source cannot tell you when something happened, only that it
    /// had happened by the time you asked. Recording the request stamp as well
    /// as the response stamp bounds the change between two instants the
    /// recorder actually observed, and `unchanged_polls` says how wide that
    /// bound is. Pretending a poll is an event timestamp is the easiest way to
    /// manufacture an edge that is not there.
    Poll {
        status: u16,
        requested: Stamp,
        unchanged_polls: u64,
        body: String,
        body_is_json: bool,
    },
}

impl Payload {
    /// Classifies an incoming frame. Validation is deliberate: a line that is
    /// not valid JSON would otherwise corrupt the record it is spliced into.
    pub fn from_frame(body: String) -> Self {
        match serde_json::from_str::<&RawValue>(&body) {
            Ok(_) => Self::Json(body),
            Err(_) => Self::Text(body),
        }
    }

    pub fn control(kind: &'static str) -> Self {
        Self::Control { kind, detail: None }
    }

    pub fn control_with(kind: &'static str, detail: impl Into<String>) -> Self {
        Self::Control {
            kind,
            detail: Some(detail.into()),
        }
    }

    pub fn label(id: impl Into<String>, direction: impl Into<String>, clicked: Stamp) -> Self {
        Self::Label {
            id: id.into(),
            direction: direction.into(),
            clicked,
        }
    }

    pub fn poll(status: u16, requested: Stamp, unchanged_polls: u64, body: String) -> Self {
        let body_is_json = serde_json::from_str::<&RawValue>(&body).is_ok();
        Self::Poll {
            status,
            requested,
            unchanged_polls,
            body,
            body_is_json,
        }
    }
}

/// One line of the recording.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Capture {
    pub seq: u64,
    pub stamp: Stamp,
    pub payload: Payload,
}

impl Capture {
    pub fn new(seq: u64, stamp: Stamp, payload: Payload) -> Self {
        Self {
            seq,
            stamp,
            payload,
        }
    }

    /// Appends this record to `out` as a single JSON line, newline included.
    pub fn write_line(&self, out: &mut String) {
        let Stamp { unix_ns, mono_ns } = self.stamp;
        let _ = write!(
            out,
            r#"{{"seq":{},"t_unix_ns":{unix_ns},"t_mono_ns":{mono_ns},"#,
            self.seq
        );
        match &self.payload {
            Payload::Json(body) => {
                out.push_str(r#""kind":"data","payload":"#);
                out.push_str(body.trim());
            }
            Payload::Text(body) => {
                out.push_str(r#""kind":"text","payload":"#);
                push_json_string(out, body);
            }
            Payload::Control { kind, detail } => {
                out.push_str(r#""kind":"control","control":"#);
                push_json_string(out, kind);
                if let Some(detail) = detail {
                    out.push_str(r#","detail":"#);
                    push_json_string(out, detail);
                }
            }
            Payload::Label {
                id,
                direction,
                clicked,
            } => {
                out.push_str(r#""kind":"label","label":"#);
                push_json_string(out, id);
                out.push_str(r#","direction":"#);
                push_json_string(out, direction);
                let _ = write!(
                    out,
                    r#","t_click_unix_ns":{},"t_click_mono_ns":{}"#,
                    clicked.unix_ns, clicked.mono_ns
                );
            }
            Payload::Poll {
                status,
                requested,
                unchanged_polls,
                body,
                body_is_json,
            } => {
                let _ = write!(
                    out,
                    r#""kind":"poll","status":{status},"t_request_unix_ns":{},"t_request_mono_ns":{},"unchanged_polls":{unchanged_polls},"payload":"#,
                    requested.unix_ns, requested.mono_ns
                );
                if *body_is_json {
                    out.push_str(body.trim());
                } else {
                    push_json_string(out, body);
                }
            }
        }
        out.push_str("}\n");
    }
}

fn push_json_string(out: &mut String, value: &str) {
    match serde_json::to_string(value) {
        Ok(encoded) => out.push_str(&encoded),
        // `to_string` on a `&str` cannot fail, but a recorder must never panic
        // on a malformed frame: losing one line beats losing the recording.
        Err(_) => out.push_str("\"\""),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stamp() -> Stamp {
        Stamp {
            unix_ns: 1_700_000_000_000_000_000,
            mono_ns: 42,
        }
    }

    fn line(payload: Payload) -> String {
        let mut out = String::new();
        Capture::new(7, stamp(), payload).write_line(&mut out);
        out
    }

    #[test]
    fn json_frames_are_stored_verbatim() {
        let out = line(Payload::from_frame(r#"{"event_type":"book"}"#.into()));
        assert_eq!(
            out,
            "{\"seq\":7,\"t_unix_ns\":1700000000000000000,\"t_mono_ns\":42,\
             \"kind\":\"data\",\"payload\":{\"event_type\":\"book\"}}\n"
        );
    }

    #[test]
    fn non_json_frames_are_escaped_as_text() {
        let out = line(Payload::from_frame("PONG".into()));
        assert!(out.contains(r#""kind":"text","payload":"PONG""#));
    }

    #[test]
    fn control_markers_carry_an_optional_detail() {
        assert!(line(Payload::control("connected")).contains(r#""control":"connected"}"#));
        let out = line(Payload::control_with("disconnected", "reset by peer"));
        assert!(out.contains(r#""control":"disconnected","detail":"reset by peer""#));
    }

    #[test]
    fn polls_record_both_ends_of_the_detection_window() {
        let requested = Stamp {
            unix_ns: 1_699_999_999_000_000_000,
            mono_ns: 11,
        };
        let out = line(Payload::poll(200, requested, 3, r#"{"score":1}"#.into()));
        assert!(out.contains(r#""kind":"poll","status":200"#));
        assert!(out.contains(r#""t_request_unix_ns":1699999999000000000"#));
        assert!(out.contains(r#""t_request_mono_ns":11"#));
        assert!(out.contains(r#""unchanged_polls":3"#));
        assert!(out.contains(r#""payload":{"score":1}"#));
    }

    #[test]
    fn poll_bodies_that_are_not_json_are_escaped() {
        let out = line(Payload::poll(503, stamp(), 0, "<html>down</html>".into()));
        assert!(out.contains(r#""payload":"<html>down</html>""#));
    }

    #[test]
    fn labels_keep_the_click_apart_from_the_write() {
        let clicked = Stamp {
            unix_ns: 1_699_999_999_000_000_000,
            mono_ns: 5,
        };
        let out = line(Payload::label("blue_fight", "up", clicked));
        assert!(out.contains(r#""kind":"label","label":"blue_fight""#));
        assert!(out.contains(r#""direction":"up""#));
        assert!(out.contains(r#""t_click_unix_ns":1699999999000000000"#));
    }

    #[test]
    fn every_line_is_valid_json_and_ends_with_a_newline() {
        for payload in [
            Payload::from_frame(r#"{"a":[1,2,{"b":"\"quoted\""}]}"#.into()),
            Payload::from_frame("not json at all \" \n".into()),
            Payload::control("connected"),
            Payload::control_with("disconnected", "weird \" detail\n"),
            Payload::poll(200, stamp(), 7, r#"[{"ok":true}]"#.into()),
            Payload::poll(500, stamp(), 0, "broken \" body".into()),
            Payload::label("odd \" id", "up", stamp()),
        ] {
            let out = line(payload);
            assert!(out.ends_with('\n'));
            serde_json::from_str::<serde_json::Value>(out.trim_end()).unwrap();
        }
    }
}
